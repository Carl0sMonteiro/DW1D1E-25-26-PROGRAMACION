package UT4.ejercicios;

public class perro {
	private String nombre;
	private String raza;
	private String propetario;
	private String edadanios;
	private String pesoKG;
	
	public String getNombre() {
		return nombre;
	}
	public void setNombre(String nombre) {
		this.nombre = nombre;
	}
	public String getRaza() {
		return raza;
	}
	public void setRaza(String raza) {
		this.raza = raza;
	}
	public String getPropetario() {
		return propetario;
	}
	public void setPropetario(String propetario) {
		this.propetario = propetario;
	}
	public String getEdadanios() {
		return edadanios;
	}
	public void setEdadanios(String edadanios) {
		this.edadanios = edadanios;
	}
	public String getPesoKG() {
		return pesoKG;
	}
	public void setPesoKG(String pesoKG) {
		this.pesoKG = pesoKG;
	}
	}

 